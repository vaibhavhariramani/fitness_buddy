/// The app's spacing scale — every screen-level gap should come from here
/// rather than a hand-picked number, so rhythm stays consistent across
/// screens built at different times.
class AppSpacing {
  const AppSpacing._();

  static const xxs = 4.0;
  static const xs = 8.0;
  static const sm = 12.0;
  static const md = 16.0;
  static const lg = 20.0;
  static const xl = 24.0;
  static const xxl = 32.0;
  static const xxxl = 40.0;
  static const section = 48.0;
}
